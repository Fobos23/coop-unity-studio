#!/usr/bin/env python
"""The studio learns, with the director's approval (references/learning.md).

  learn.py status                                   pending proposals and accepted-but-not-applied lessons
  learn.py propose --title T --kind technique|tool|process|fix --what W --when C --why Y
                   [--phase N] [--source S] [--project NAME]
                                                    queue a general lesson (duplicates are refused)
  learn.py list [--status pending|accepted|applied|rejected]
  learn.py accept ID                                the director said yes: apply it to the studio next
  learn.py applied ID --where <file in the studio> [--commit SHA]
                                                    the edit is in the studio files (and committed)
  learn.py reject ID --why "…"                      the director said no; never proposed again
  learn.py prefer "text" (--project <path> | --global)
                                                    a director's rule: for one game into its CLAUDE.md, or for every
                                                    game (how to work with the director, never taste)
  learn.py unprefer "<part of the text>" (--project <path> | --global)

Data lives next to this skill: learned/lessons.jsonl, learned/INDEX.md (generated), learned/preferences.md.
"""
import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
DIR = SKILL / "learned"
LESSONS = DIR / "lessons.jsonl"
INDEX = DIR / "INDEX.md"
PREFS = DIR / "preferences.md"
STOP = {"the", "a", "an", "of", "to", "in", "on", "for", "and", "or", "with", "is", "it", "be", "by", "at", "as",
        "when", "use", "not", "no", "do", "from", "into", "than", "that", "this"}

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8" if not _s.isatty() else _s.encoding, errors="replace")
    except (AttributeError, ValueError, OSError):
        pass


def load():
    if not LESSONS.exists():
        return []
    return [json.loads(ln) for ln in LESSONS.read_text(encoding="utf-8").splitlines() if ln.strip()]


def save(items):
    DIR.mkdir(parents=True, exist_ok=True)
    LESSONS.write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in items), encoding="utf-8")
    write_index(items)


def write_index(items):
    by = lambda s: [x for x in items if x["status"] == s]
    lines = ["# What the studio learned", "",
             "Generated by `scripts/learn.py`. Accepted lessons not yet applied override the general text of the skill",
             "until they are written into it. Rejected ones stay so they are not proposed again.", ""]
    for title, status in (("Accepted, to apply", "accepted"), ("Pending (ask the director at the end of a phase or session)", "pending"),
                          ("Applied", "applied"), ("Rejected", "rejected")):
        rows = by(status)
        lines.append(f"## {title} ({len(rows)})")
        for x in rows:
            extra = {"applied": f" → {x.get('where', '')}", "rejected": f" — no: {x.get('why_not', '')}"}.get(status, "")
            lines.append(f"- **{x['id']}** [{x['kind']}{', phase ' + str(x['phase']) if x.get('phase') else ''}] "
                         f"{x['title']}: {x['what']} — when: {x['when']}{extra}")
        lines.append("")
    INDEX.write_text("\n".join(lines), encoding="utf-8")


def words(s):
    return {w for w in re.findall(r"[a-zа-яё0-9]+", s.lower()) if w not in STOP and len(w) > 2}


def similar(a, b):
    wa, wb = words(a), words(b)
    if not wa or not wb:
        return 0.0
    return len(wa & wb) / min(len(wa), len(wb))


def find(items, ident):
    for x in items:
        if x["id"].lower() == ident.lower():
            return x
    sys.exit(f"no lesson {ident}")


def cmd_propose(a):
    items = load()
    text = f"{a.title} {a.what}"
    for x in items:
        s = max(similar(text, f"{x['title']} {x['what']}"), similar(a.title, x["title"]))
        if s >= 0.6:
            sys.exit(f"similar to {x['id']} ({x['status']}): {x['title']} — not added")
    ident = f"L{len(items) + 1:03d}"
    items.append({"id": ident, "status": "pending", "date": date.today().isoformat(), "title": a.title, "kind": a.kind,
                  "phase": a.phase, "what": a.what, "when": a.when, "why": a.why, "source": a.source,
                  "project": a.project})
    save(items)
    print(f"{ident} queued: {a.title}. Ask the director at the end of the phase or session.")


def cmd_list(a):
    items = [x for x in load() if not a.status or x["status"] == a.status]
    for x in items:
        print(f"{x['id']} {x['status']:<8} [{x['kind']}] {x['title']} — {x['what']}")
    print(f"{len(items)} lessons")


def cmd_status(_):
    items = load()
    pend = [x for x in items if x["status"] == "pending"]
    acc = [x for x in items if x["status"] == "accepted"]
    print(f"studio lessons: {len(pend)} pending, {len(acc)} accepted but not applied, "
          f"{sum(x['status'] == 'applied' for x in items)} applied, {sum(x['status'] == 'rejected' for x in items)} rejected")
    for x in acc:
        print(f"  TO APPLY {x['id']}: {x['title']} — {x['what']}")
    for x in pend:
        print(f"  pending  {x['id']}: {x['title']}")
    prefs = PREFS.read_text(encoding="utf-8").strip() if PREFS.exists() else ""
    rules = [ln for ln in prefs.splitlines() if ln.startswith("- ")]
    print(f"global director preferences: {len(rules)}" + ("".join(f"\n  {r}" for r in rules)))


def set_status(a, status, **kw):
    items = load()
    x = find(items, a.id)
    x["status"] = status
    x.update({k: v for k, v in kw.items() if v})
    x[f"{status}_on"] = date.today().isoformat()
    save(items)
    return x


def cmd_accept(a):
    x = set_status(a, "accepted")
    print(f"{x['id']} accepted. Now write it into the studio (the smallest edit in the right file), check it, commit in "
          f"the studio repo 'learn {x['id']}: {x['title']}', then: learn.py applied {x['id']} --where <file> --commit <sha>")


def cmd_applied(a):
    x = set_status(a, "applied", where=a.where, commit=a.commit)
    print(f"{x['id']} applied in {a.where}")


def cmd_reject(a):
    x = set_status(a, "rejected", why_not=a.why)
    print(f"{x['id']} rejected: {a.why}")


def pref_file(a):
    if a.glob:
        return PREFS, "# Director's preferences for every game\n\nHow to work with the director (never taste). Read at session start.\n"
    if not a.project:
        sys.exit("say where: --project <game folder> (this game only) or --global (every game)")
    p = Path(a.project) / "CLAUDE.md"
    if not p.exists():
        sys.exit(f"no {p}")
    return p, None


SECTION = "## Director's preferences"


def cmd_prefer(a):
    path, header = pref_file(a)
    line = f"- {a.text.strip()} ({date.today().isoformat()})"
    if header is not None:
        text = path.read_text(encoding="utf-8") if path.exists() else header
        if a.text.strip() in text:
            sys.exit("already there")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text.rstrip("\n") + "\n" + line + "\n", encoding="utf-8")
    else:
        text = path.read_text(encoding="utf-8")
        if a.text.strip() in text:
            sys.exit("already there")
        if SECTION in text:
            head, tail = text.split(SECTION, 1)
            nxt = re.search(r"\n## ", tail)
            body, rest = (tail[:nxt.start()], tail[nxt.start():]) if nxt else (tail, "")
            text = head + SECTION + body.rstrip("\n") + "\n" + line + "\n" + rest
        else:
            text = text.rstrip("\n") + f"\n\n{SECTION}\n" + line + "\n"
        path.write_text(text, encoding="utf-8")
    print(f"saved to {path}: {line}")


def cmd_unprefer(a):
    path, _ = pref_file(a)
    if not path.exists():
        sys.exit(f"no {path}")
    lines = path.read_text(encoding="utf-8").splitlines()
    keep = [ln for ln in lines if not (ln.startswith("- ") and a.text.lower() in ln.lower())]
    if len(keep) == len(lines):
        sys.exit("no matching preference")
    path.write_text("\n".join(keep) + "\n", encoding="utf-8")
    print(f"removed {len(lines) - len(keep)} line(s) from {path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("status")
    p = sp.add_parser("propose")
    p.add_argument("--title", required=True)
    p.add_argument("--kind", required=True, choices=["technique", "tool", "process", "fix"])
    p.add_argument("--what", required=True)
    p.add_argument("--when", required=True)
    p.add_argument("--why", required=True)
    p.add_argument("--phase", type=int, default=None)
    p.add_argument("--source", default="")
    p.add_argument("--project", default="")
    p = sp.add_parser("list")
    p.add_argument("--status", choices=["pending", "accepted", "applied", "rejected"])
    for name in ("accept",):
        p = sp.add_parser(name)
        p.add_argument("id")
    p = sp.add_parser("applied")
    p.add_argument("id")
    p.add_argument("--where", required=True)
    p.add_argument("--commit", default="")
    p = sp.add_parser("reject")
    p.add_argument("id")
    p.add_argument("--why", required=True)
    for name in ("prefer", "unprefer"):
        p = sp.add_parser(name)
        p.add_argument("text")
        p.add_argument("--project", default="")
        p.add_argument("--global", dest="glob", action="store_true")
    a = ap.parse_args()
    {"status": cmd_status, "propose": cmd_propose, "list": cmd_list, "accept": cmd_accept, "applied": cmd_applied,
     "reject": cmd_reject, "prefer": cmd_prefer, "unprefer": cmd_unprefer}[a.cmd](a)


if __name__ == "__main__":
    main()
